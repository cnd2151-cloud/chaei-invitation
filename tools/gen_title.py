"""
Generate handwriting-animation data for the hero title.

Output: src/generated/titlePaths.ts
  - fill: glyph outline paths (the visible brush lettering)
  - strokes: centre-line "pen" paths (skeleton of the glyphs, ordered in
    writing order) used as an animated SVG mask -> lettering is revealed
    along its real strokes, like it is being written.

Usage (from project root):  python3 tools/gen_title.py "Chaei's" "1st Birthday"
Needs:  pip install fonttools uharfbuzz scikit-image opencv-python-headless numpy
"""
import sys, json, math
import numpy as np, cv2
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from skimage.morphology import skeletonize
from scipy import ndimage as ndi

FONT = sys.argv[3] if len(sys.argv) > 3 else 'tools/fonts/ComforterBrush-Regular.ttf'
LINES = [sys.argv[1] if len(sys.argv) > 1 else "Chaei's",
         sys.argv[2] if len(sys.argv) > 2 else "1st Birthday"]
OUT = sys.argv[4] if len(sys.argv) > 4 else 'src/generated/titlePaths.ts'

S = 0.5            # font units -> px (em = 500px raster)
LINE_GAP = 980     # baseline distance (font units)
LINE_SCALE = [1.0, 1.0]
PAD = 40
DUR = [0.75, 1.05]   # seconds per line
GAP = 0.1         # pause between lines

font = TTFont(FONT)
gs = font.getGlyphSet()
blob = hb.Blob.from_file_path(FONT)
hbfont = hb.Font(hb.Face(blob))


class FlatPen(BasePen):
    def __init__(self, gs):
        super().__init__(gs); self.contours = []; self.cur = []
    def _moveTo(self, p): self.cur = [p]
    def _lineTo(self, p): self.cur.append(p)
    def _qCurveToOne(self, p1, p2):
        p0 = self.cur[-1]
        for t in np.linspace(0, 1, 9)[1:]:
            self.cur.append(((1-t)**2*p0[0]+2*(1-t)*t*p1[0]+t*t*p2[0],
                             (1-t)**2*p0[1]+2*(1-t)*t*p1[1]+t*t*p2[1]))
    def _curveToOne(self, p1, p2, p3):
        p0 = self.cur[-1]
        for t in np.linspace(0, 1, 13)[1:]:
            a, b, c, d = (1-t)**3, 3*(1-t)**2*t, 3*(1-t)*t*t, t**3
            self.cur.append((a*p0[0]+b*p1[0]+c*p2[0]+d*p3[0], a*p0[1]+b*p1[1]+c*p2[1]+d*p3[1]))
    def _closePath(self):
        if len(self.cur) > 2: self.contours.append(self.cur)
        self.cur = []
    _endPath = _closePath


def shape(text):
    buf = hb.Buffer(); buf.add_str(text); buf.guess_segment_properties()
    hb.shape(hbfont, buf, {'kern': True, 'liga': True})
    x = 0; out = []
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        out.append((font.getGlyphName(info.codepoint), x + pos.x_offset, pos.y_offset))
        x += pos.x_advance
    return out, x

# ---- layout ----
shaped = [shape(t) for t in LINES]
widths = [w*LINE_SCALE[i] for i, (_, w) in enumerate(shaped)]
maxw = max(widths)
asc = font['hhea'].ascent
W = int(maxw*S + 2*PAD)
baselines = [PAD + asc*S*0.85, PAD + asc*S*0.85 + LINE_GAP*S]
H = int(baselines[-1] + 380*S + PAD)

fill_paths = []
masks = []
for li, (glyphs, w) in enumerate(shaped):
    sc = S*LINE_SCALE[li]
    ox = (W - w*sc)/2
    svgpen = SVGPathPen(gs, ntos=lambda v: f'{v:.1f}')
    flat = FlatPen(gs)
    for name, gx, gy in glyphs:
        t = (sc, 0, 0, -sc, ox + gx*sc, baselines[li] - gy*sc)
        gs[name].draw(TransformPen(svgpen, t))
        gs[name].draw(TransformPen(flat, t))
    fill_paths.append(svgpen.getCommands())
    # nonzero-winding raster
    acc = np.zeros((H, W), np.int16)
    for c in flat.contours:
        tmp = np.zeros((H, W), np.uint8)
        pts = np.round(np.array(c)*4).astype(np.int32)
        cv2.fillPoly(tmp, [pts], 1, lineType=cv2.LINE_8, shift=2)
        area = 0.5*sum(c[i][0]*c[(i+1) % len(c)][1]-c[(i+1) % len(c)][0]*c[i][1] for i in range(len(c)))
        acc += tmp.astype(np.int16)*(1 if area > 0 else -1)
    m = acc != 0
    m = ndi.binary_closing(m, iterations=2)
    masks.append(m)

from strokelib import trace, timeline, smooth_path

strokes_out = []
t0 = 0.0
for li, m in enumerate(masks):
    st, t = timeline(trace(m), t0, DUR[li])
    for s in st: s['line'] = li
    strokes_out += st
    t0 = t + GAP

data = dict(viewBox=f'0 0 {W} {H}', width=W, height=H, text=LINES,
            fill=fill_paths, strokes=strokes_out, total=round(t0 - GAP, 3))
with open(OUT, 'w') as f:
    f.write('// AUTO-GENERATED by tools/gen_title.py — do not edit by hand.\n')
    f.write('// Regenerate:  python3 tools/gen_title.py "Chaei\'s" "1st Birthday"\n')
    f.write('export const TITLE = ' + json.dumps(data) + ' as const;\n')
print('strokes', len(strokes_out), 'size', W, H, 'total', data['total'])

# debug preview
dbg = np.full((H, W, 3), 255, np.uint8)
for m in masks: dbg[m] = (220, 220, 220)
for i, s in enumerate(strokes_out):
    col = tuple(int(c) for c in cv2.cvtColor(np.uint8([[[int(180*i/len(strokes_out)), 255, 200]]]), cv2.COLOR_HSV2BGR)[0, 0])
    import re
    nums = [float(v) for v in re.findall(r'-?\d+\.?\d*', s['d'])]
    xy = np.array(nums).reshape(-1, 2).astype(np.int32)
    cv2.polylines(dbg, [xy], False, col, 2)
    cv2.putText(dbg, str(i), tuple(int(v) for v in xy[0]), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 0, 0), 1)
cv2.imwrite('/tmp/claude-0/-home-user/874364ac-a8e8-52c3-b4db-8cf02aae2af0/scratchpad/title_dbg.png', dbg)
