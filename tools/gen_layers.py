"""
메인 비주얼 레이어 생성기
---------------------------------------------------------------
분리된 원본 요소(아기/풍선/곰인형/컵케이크/손그림)를 레퍼런스 구도
(tools/source/main-reference.webp)와 같은 위치·크기로 배치할 수 있게
웹용 이미지와 위치값(src/generated/layers.ts)을 만든다.

  python3 tools/gen_layers.py

입력  tools/source/layers/{baby,balloon,bear,cupcake}-trim.png  (투명 배경, 여백 제거)
      tools/source/layers/doodles.png   (왕관 + Let's Party! 손그림, 흰 배경)
      tools/source/layers/match.json    (레퍼런스 기준 위치/크기; tools/match_layers.py 로 계산)
출력  public/images/main/*.webp|png, src/generated/layers.ts

요소를 교체할 때: 같은 이름으로 *-trim.png 를 바꾸고 match.json 의 x/y/w/h 를 조정한 뒤 다시 실행.
"""
import os, sys, json
import numpy as np, cv2
from PIL import Image
from scipy import ndimage as ndi
sys.path.insert(0, os.path.dirname(__file__))
from strokelib import trace, timeline

SRC = 'tools/source/main-reference.webp'
L = 'tools/source/layers'
OUT = 'public/images/main'
CANVAS = dict(x=230, y=100, w=1070, h=1065)   # 레퍼런스 이미지 좌표계에서 메인 비주얼 영역
EXPORT = 1.5                                   # 레퍼런스 px 대비 내보내기 배율 (고해상도 화면 대응)
ORDER = ['balloon', 'bear', 'cupcake', 'baby']  # 뒤 → 앞

os.makedirs(OUT, exist_ok=True)
m = json.load(open(f'{L}/match.json'))
boxes = {}
comp = Image.new('RGBA', (CANVAS['w'], CANVAS['h']), (0, 0, 0, 0))
for n in ORDER:
    v = m[n]
    im = Image.open(f'{L}/{n}-trim.png').convert('RGBA')
    w, h = round(v['w'] * EXPORT), round(v['h'] * EXPORT)
    im.resize((w, h), Image.LANCZOS).save(f'{OUT}/{n}.webp', quality=88, method=6)
    boxes[n] = dict(left=(v['x'] - CANVAS['x']) / CANVAS['w'] * 100, top=(v['y'] - CANVAS['y']) / CANVAS['h'] * 100,
                    width=v['w'] / CANVAS['w'] * 100, height=v['h'] / CANVAS['h'] * 100)
    comp.alpha_composite(im.resize((round(v['w']), round(v['h'])), Image.LANCZOS),
                         (round(v['x'] - CANVAS['x']), round(v['y'] - CANVAS['y'])))
comp.save('tools/source/_composite.png')   # 샘플 사진/공유 썸네일 생성용

# ---------- 손그림 (왕관 · Let's Party! · 하트) ----------
def ink_layer(gray, rgb_like=None):
    """흰 배경 위 검은 잉크 → 알파"""
    a = np.clip((205 - gray) / 170, 0, 1)
    return a

doodles = []
dd = m['doodles']; ds = dd['scale']
sheet = np.array(Image.open(f'{L}/doodles.png').convert('L')).astype(np.float32)
# sheet 안에서 각 요소의 영역 (sheet px)
parts = {'crown': (60, 140, 250, 330), 'party': (255, 150, 560, 525)}
specs = {'crown': ((1, 0), 0.95, 0.55), 'party': ((0.62, 0.79), 1.6, 1.05)}
for name, (x0, y0, x1, y1) in parts.items():
    g = sheet[y0:y1, x0:x1]
    a = ink_layer(g)
    W, H = round((x1 - x0) * ds * EXPORT), round((y1 - y0) * ds * EXPORT)
    img = np.zeros((y1 - y0, x1 - x0, 4), np.uint8); img[..., :3] = 30; img[..., 3] = (a * 255).astype(np.uint8)
    Image.fromarray(img, 'RGBA').resize((W, H), Image.LANCZOS).save(f'{OUT}/doodle-{name}.png', optimize=True)
    # 획 중심선 (레퍼런스 좌표)
    core = ndi.binary_closing(a > 0.45, iterations=1)
    lab, k = ndi.label(core); sz = ndi.sum(core, lab, range(1, k + 1))
    core = np.isin(lab, [i + 1 for i, s in enumerate(sz) if s > 12])
    big = cv2.resize(core.astype(np.uint8), None, fx=ds, fy=ds, interpolation=cv2.INTER_NEAREST) > 0
    dirv, start, dur = specs[name]
    dv = np.array(dirv, float); dv /= np.linalg.norm(dv)
    st = trace(big, tuple(dv))
    ox, oy = dd['x'] + x0 * ds, dd['y'] + y0 * ds
    st = [(arr + np.array([ox, oy]), w + 5) for arr, w in st]
    tl, _ = timeline(st, start, dur)
    doodles.append(dict(name=name, x=round(ox, 1), y=round(oy, 1), w=round((x1 - x0) * ds, 1), h=round((y1 - y0) * ds, 1),
                        src=f'/images/main/doodle-{name}.png', strokes=tl))
    print(name, len(tl), 'strokes')

# 하트: 분리 요소에 없어 레퍼런스에서 추출
ref = np.array(Image.open(SRC).convert('RGB')).astype(int)
hx0, hy0, hx1, hy1 = 320, 470, 475, 630
g = ref[hy0:hy1, hx0:hx1].mean(-1); sat = (ref[hy0:hy1, hx0:hx1].max(-1) - ref[hy0:hy1, hx0:hx1].min(-1))
a = np.clip((200 - g) / 160, 0, 1) * (sat < 50)
img = np.zeros((hy1 - hy0, hx1 - hx0, 4), np.uint8); img[..., :3] = 30; img[..., 3] = (a * 255).astype(np.uint8)
Image.fromarray(img, 'RGBA').resize((round((hx1 - hx0) * EXPORT), round((hy1 - hy0) * EXPORT)), Image.LANCZOS).save(f'{OUT}/doodle-heart.png', optimize=True)
core = ndi.binary_closing(a > 0.45, iterations=1)
st = [(arr + np.array([hx0, hy0]), w + 5) for arr, w in trace(core, (0.2, 1))]
tl, _ = timeline(st, 1.25, 0.6)
doodles.append(dict(name='heart', x=hx0, y=hy0, w=hx1 - hx0, h=hy1 - hy0, src='/images/main/doodle-heart.png', strokes=tl))
print('heart', len(tl), 'strokes')

with open('src/generated/layers.ts', 'w') as f:
    f.write('// AUTO-GENERATED by tools/gen_layers.py — do not edit by hand.\n')
    f.write('export const CANVAS = ' + json.dumps(CANVAS) + ' as const;\n')
    f.write('export const LAYER_ORDER = ' + json.dumps(ORDER) + ' as const;\n')
    f.write('export const LAYER_BOX: Record<string, { left: number; top: number; width: number; height: number }> = '
            + json.dumps({k: {kk: round(vv, 3) for kk, vv in v.items()} for k, v in boxes.items()}) + ';\n')
    f.write('export const DOODLES = ' + json.dumps(doodles) + ';\n')
print('done')
